"""Phase 1: exploratory data analysis of NHAMCS ED (DEV split only, 2016-2021).

The 2022 test split is NOT explored, so nothing we learn here can leak into model choices.

Output: reports/figures/p1_*.png  and  reports/phase1_data_summary.md
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"
FIG = ROOT / "reports" / "figures"

ORDER = ["ROUTINE", "URGENT", "EMERGENCY"]
# Ordinal single-hue ramp (light -> dark = less -> more urgent); validated with the
# dataviz palette checker (--ordinal, light surface): all checks pass.
COLORS = {"ROUTINE": "#86b6ef", "URGENT": "#2a78d6", "EMERGENCY": "#104281"}
SURFACE, INK, INK2, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9"

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": "#c3c2b7", "axes.labelcolor": INK2, "xtick.color": MUTED, "ytick.color": MUTED,
    "text.color": INK, "font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "axes.axisbelow": True, "grid.color": GRID, "grid.linewidth": 0.6,
})


def stacked_share(ax, table: pd.DataFrame, title: str, xlabel: str) -> None:
    """100% stacked horizontal bars; 2px surface gaps between segments; legend + labels >= 8%."""
    share = table.div(table.sum(axis=1), axis=0) * 100
    left = pd.Series(0.0, index=share.index)
    for cls in ORDER:
        vals = share[cls]
        ax.barh(share.index.astype(str), vals, left=left, color=COLORS[cls], label=cls.title(),
                edgecolor=SURFACE, linewidth=2, height=0.7)
        for i, (v, l) in enumerate(zip(vals, left)):
            if v >= 8:
                ax.text(l + v / 2, i, f"{v:.0f}%", ha="center", va="center", fontsize=8,
                        color="#0b0b0b" if cls == "ROUTINE" else "#ffffff")
        left += vals
    ax.set_xlim(0, 100)
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    ax.set_xlabel(xlabel)
    ax.grid(axis="y", visible=False)
    ax.invert_yaxis()
    ax.legend(ncol=3, loc="upper left", bbox_to_anchor=(0, -0.18), frameon=False)


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(PROC / "nhamcs_ed.csv.gz")
    dev = df[df["SPLIT"] == "dev"].copy()
    rfv = pd.read_csv(PROC / "rfv_codes.csv").set_index("code")["label"]
    audit = pd.read_csv(PROC / "label_audit.csv")
    lines = ["# Phase 1 - NHAMCS ED data summary (generated by scripts/explore_nhamcs.py)", "",
             "Source: CDC/NCHS NHAMCS Emergency Department public-use files 2016-2022 (public domain).",
             "Analysis below uses the **dev split (2016-2021) only**; 2022 is the untouched test set.", ""]

    # --- 1. Label availability (all years, counts only - no outcome information) ----------
    pivot = audit.pivot_table(index="year", columns="meaning", values="n", aggfunc="sum").fillna(0).astype(int)
    lines += ["## 1. Triage-label availability per year (all visits)", "", pivot.to_markdown(), ""]

    # --- 2. Urgency by year --------------------------------------------------------------------
    by_year = pd.crosstab(dev["YEAR"], dev["URGENCY"])[ORDER]
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    stacked_share(ax, by_year, "Urgency mix of triaged ED visits by year (dev split)", "Share of visits (%)")
    fig.tight_layout(); fig.savefig(FIG / "p1_urgency_by_year.png", dpi=150); plt.close(fig)
    lines += ["## 2. Urgency distribution (dev)", "", by_year.assign(TOTAL=by_year.sum(axis=1)).to_markdown(), "",
              f"Overall: " + ", ".join(f"{c.title()} {v:.1%}" for c, v in dev['URGENCY'].value_counts(normalize=True)[ORDER].items()), ""]

    # --- 3. Pain score vs urgency -------------------------------------------------------------
    bins = pd.cut(dev["PAINSCALE"], [-0.5, 0.5, 3.5, 6.5, 10.5], labels=["0 none", "1-3 mild", "4-6 moderate", "7-10 severe"])
    dev["PAIN_BAND"] = bins.cat.add_categories("missing").fillna("missing").astype(str)
    pain = pd.crosstab(dev["PAIN_BAND"], dev["URGENCY"])[ORDER].reindex(["0 none", "1-3 mild", "4-6 moderate", "7-10 severe", "missing"])
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    stacked_share(ax, pain, "Urgency mix by reported pain score (dev split)", "Share of visits (%)")
    fig.tight_layout(); fig.savefig(FIG / "p1_urgency_by_pain.png", dpi=150); plt.close(fig)
    lines += ["## 3. Pain score vs urgency (dev)", "", pain.assign(TOTAL=pain.sum(axis=1)).to_markdown(), ""]

    # --- 4. Most common first reasons for visit and their emergency share ---------------------
    top = dev["RFV1"].value_counts().head(15)
    em = dev[dev["RFV1"].isin(top.index)].groupby("RFV1")["URGENCY"].apply(lambda s: (s == "EMERGENCY").mean() * 100)
    t = pd.DataFrame({"n": top, "emergency_pct": em}).sort_values("emergency_pct")
    t["label"] = [f"{str(rfv.get(int(c), c))[:38]}  (n={n:,})" for c, n in zip(t.index, t["n"])]
    fig, ax = plt.subplots(figsize=(8, 5.5))
    ax.barh(t["label"], t["emergency_pct"], color=COLORS["URGENT"], height=0.6)
    for i, v in enumerate(t["emergency_pct"]):
        ax.text(v + 0.8, i, f"{v:.0f}%", va="center", fontsize=8, color=INK2)
    fig.suptitle("Emergency share, 15 most common reasons for visit (dev)", x=0.01, ha="left", fontsize=11)
    ax.set_xlabel("Visits triaged Immediate/Emergent (%)")
    ax.grid(axis="y", visible=False)
    fig.tight_layout(); fig.savefig(FIG / "p1_top_rfv_emergency_share.png", dpi=150); plt.close(fig)
    t_out = t.reset_index().rename(columns={"RFV1": "rfv_code"})
    t_out["reason"] = [rfv.get(int(c), "?") for c in t_out["rfv_code"]]
    lines += ["## 4. Top-15 first reasons for visit (dev)", "",
              t_out[["rfv_code", "reason", "n", "emergency_pct"]].sort_values("n", ascending=False).round(1).to_markdown(index=False), ""]

    # --- 5. Missingness & RFV types -------------------------------------------------------------
    miss = (dev[["AGE", "SEX", "PAINSCALE", "RFV1", "RFV2", "RFV3"]].isna().mean() * 100).round(1)
    rfv_all = dev[[f"RFV{i}" for i in range(1, 6)]].stack().dropna()  # pandas 3 keeps NaN in stack()
    symptom_share = ((rfv_all >= 10000) & (rfv_all < 20000)).mean() * 100
    lines += ["## 5. Missing values (dev, %)", "", miss.to_frame("missing_%").to_markdown(), "",
              f"- Reason-for-visit codes in the **symptom module (10000-19999)**: {symptom_share:.1f}% of all coded reasons.",
              f"- Mean number of coded reasons per visit: {dev[[f'RFV{i}' for i in range(1, 6)]].notna().sum(axis=1).mean():.2f}",
              f"- Age: median {dev['AGE'].median():.0f}, range {dev['AGE'].min():.0f}-{dev['AGE'].max():.0f}", ""]

    (ROOT / "reports" / "phase1_data_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
